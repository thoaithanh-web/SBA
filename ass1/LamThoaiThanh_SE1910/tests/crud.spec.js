import { test, expect } from '@playwright/test'
import { createCategory, createUser, login, openCreate } from './helpers'

test.beforeEach(async ({ page }) => {
  await login(page)
})

test('category create, search, update, cancel delete and confirm delete', async ({ page }) => {
  await createCategory(page, 'Editorial lab')
  await page.getByLabel('Search categories').fill('  EDITORIAL LAB  ')
  await expect(page.getByRole('row')).toHaveCount(2)
  await page.getByRole('button', { name: 'Edit category Editorial lab', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Category name')).toHaveValue('Editorial lab')
  await dialog.getByLabel('Category name').fill('Editorial studio')
  await dialog.getByLabel('Status', { exact: true }).selectOption('0')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByRole('heading', { name: 'No results found' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await page.getByRole('button', { name: 'Delete category Editorial studio', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByText('Editorial studio', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Delete category Editorial studio', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByText('Editorial studio', { exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByText('Editorial studio', { exact: true })).toHaveCount(0)
})

test('news CRUD, preview, relationships and persistence', async ({ page }) => {
  await createCategory(page, 'Editorial lab')
  await createUser(page)
  await page.goto('/news')
  let dialog = await openCreate(page, 'New article')
  await dialog.getByLabel('Article title').fill('A test story')
  await dialog.getByLabel('Category', { exact: true }).selectOption({ label: 'Editorial lab' })
  await dialog.getByLabel('Author', { exact: true }).selectOption({ label: 'Test Editor' })
  await dialog.getByLabel('Article content').fill('A useful campus story.\nA second paragraph.')
  await dialog.getByLabel('Tags', { exact: true }).fill('test, campus, test')
  await dialog.getByRole('button', { name: 'Create article', exact: true }).click()
  await page.getByLabel('Search news').fill('a test story')
  await expect(page.getByRole('row')).toHaveCount(2)
  await page.getByRole('button', { name: 'Read article A test story', exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name: 'A test story', exact: true })).toBeVisible()
  await expect(dialog.getByText('#test', { exact: true })).toHaveCount(1)
  await expect(dialog.getByText('A useful campus story.', { exact: false })).toBeVisible()
  await dialog.getByRole('button', { name: 'Close preview' }).click()
  await page.getByRole('button', { name: 'Edit article A test story', exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Article content')).toHaveValue(
    'A useful campus story.\nA second paragraph.',
  )
  await dialog.getByLabel('Publication status').selectOption('1')
  await dialog.getByLabel('Article title').fill('A test story updated')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await page.reload()
  const row = page.getByRole('row').filter({ hasText: 'A test story updated' })
  await expect(row).toContainText('Published')
  await expect(row).toContainText('Editorial lab')
  await expect(row).toContainText('Test Editor')
  await row.getByRole('button', { name: /^Delete article/ }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: /^Delete article/ }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(row).toHaveCount(0)
})

test('user CRUD and role/status labels', async ({ page }) => {
  let row = await createUser(page)
  await expect(row).toContainText('Staff')
  await expect(row).toContainText('Active')
  await page.getByLabel('Search users').fill('  TEST.EDITOR  ')
  await expect(page.getByRole('row')).toHaveCount(2)
  await page.getByRole('button', { name: 'Edit user test.editor', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Full name')).toHaveValue('Test Editor')
  await dialog.getByLabel('Full name').fill('Updated Editor')
  await dialog.getByLabel('Role', { exact: true }).selectOption('1')
  await dialog.getByLabel('Status', { exact: true }).selectOption('0')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await page.reload()
  row = page.getByRole('row').filter({ hasText: 'test.editor' })
  await expect(row).toContainText('Updated Editor')
  await expect(row).toContainText('Admin')
  await expect(row).toContainText('Inactive')
  await row.getByRole('button', { name: 'Delete user test.editor', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'Delete user test.editor', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(row).toHaveCount(0)
})

